public class Escape {
    public static void main(String[] args){
        System.out.println("welcome \"vishal\" ");
        System.out.println("welcome \n \\vishal\\ ");
        System.out.println("welcome \t \\vishal\\ ");
        System.out.println("welcome\bvishal ");
        System.out.println("welcomevishal");
        System.out.println("welcome vishal ");
    }
}
